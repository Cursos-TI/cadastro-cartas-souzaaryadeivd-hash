#include <stdio.h>

int main () {
    int numeroNormal = 50000000000000;
    long int numeroGrande = 500000000000000;
    long long int numeroExGrande = 500000000000000000;

    printf ("Numero regular (int): %d\n", numeroNormal);
    printf ("Numero regular (long int): %ld\n", numeroGrande);
    printf ("Numero regular (long long int): %lld\n", numeroExGrande);


    return 0;

}