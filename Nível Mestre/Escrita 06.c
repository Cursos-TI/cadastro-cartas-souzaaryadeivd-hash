# include <stdio.h>

int main () {
    unsigned long int numeroGrandePositivo = 40000000000;
    unsigned int numeroPositivo = 4000000000000;
    long int numeroGrande = 4000000000;
    int numero = 40000000000;

    printf ("Numero grande positivo (unsigned long int): %lu\n", numeroGrandePositivo);
    printf ("Numero positivo ( unsigned int): %u\n", numeroPositivo);
    printf ("Numero grande (long int): %ld\n", numeroGrande);
    printf ("Numero (int): %d\n", numero);

    return 0;


}